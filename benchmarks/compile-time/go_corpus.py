"""Emit a Go program shaped like corpus/: one package per Raven module with
the same structs, methods, enums, generics, interface, loops, and recursion,
plus a main that calls every compute function. Used to compare compile time
with Go; see README.md.

Usage: python go_corpus.py [module_count] [output_dir]
"""
import os
import shutil
import sys

COUNT = int(sys.argv[1]) if len(sys.argv) > 1 else 62
root = sys.argv[2] if len(sys.argv) > 2 else os.path.dirname(os.path.abspath(__file__)) + '/go-corpus'
MARKER = '.go-corpus'
if os.path.exists(root) and os.listdir(root):
    if not os.path.exists(os.path.join(root, MARKER)):
        sys.exit(f'{root} is not empty and was not made by this script; pick another directory')
    shutil.rmtree(root)
os.makedirs(root, exist_ok=True)
open(os.path.join(root, MARKER), 'w').write('generated by go_corpus.py\n')
open(root + '/go.mod', 'w').write('module corpus\n\ngo 1.21\n')


def module(i):
    # The same per-module constant generate.sh uses, so both programs match.
    base = (i * 7) % 23 + 1
    return f'''package mod{i}

type Vec2 struct {{ X, Y int }}

func (v Vec2) Add(o Vec2) Vec2   {{ return Vec2{{X: v.X + o.X, Y: v.Y + o.Y}} }}
func (v Vec2) Scale(k int) Vec2  {{ return Vec2{{X: v.X * k, Y: v.Y * k}} }}
func (v Vec2) MagnitudeSq() int  {{ return v.X*v.X + v.Y*v.Y }}

type Node struct {{
	ID, Weight int
	Label      string
}}

func (n Node) Heavier(o Node) bool   {{ return n.Weight > o.Weight }}
func (n Node) Retag(l string) Node   {{ return Node{{ID: n.ID, Weight: n.Weight, Label: l}} }}

type Shape int

const (
	Circle Shape = iota
	Square
	Triangle
	Hexagon
)

func Classify(s Shape) int {{
	switch s {{
	case Circle:
		return {base}
	case Square:
		return {base} * 2
	case Triangle:
		return {base} * 3
	default:
		return {base} * 6
	}}
}}

type Outcome int

const (
	Pass Outcome = iota
	Fail
	Skip
)

func Grade(score int) Outcome {{
	if score >= 60 {{
		return Pass
	}}
	if score >= 30 {{
		return Skip
	}}
	return Fail
}}

func GradePoints(o Outcome) int {{
	switch o {{
	case Pass:
		return 100
	case Fail:
		return 0
	default:
		return 50
	}}
}}

type Pair[T any] struct {{ First, Second T }}

func (p Pair[T]) Left() T  {{ return p.First }}
func (p Pair[T]) Right() T {{ return p.Second }}

type Wrap[T any] struct {{ Inner T }}

func (w Wrap[T]) Get() T {{ return w.Inner }}

func Mapped[T, U any](w Wrap[T], f func(T) U) U {{ return f(w.Inner) }}

type Score interface{{ Score() int }}

func (n Node) Score() int {{ return n.ID*10 + n.Weight }}
func (v Vec2) Score() int {{ return v.MagnitudeSq() }}

func Ranked[T Score](x T) int {{ return x.Score() }}

func Identity[T any](x T) T {{ return x }}

func Maybe(n int) *int {{
	if n > {base} {{
		v := n * 2
		return &v
	}}
	return nil
}}

func UnwrapOr(x *int, fallback int) int {{
	if x == nil {{
		return fallback
	}}
	return *x
}}

func Accumulate(limit int) int {{
	total := 0
	for i := 0; i < limit; i++ {{
		if i%2 == 0 {{
			total += i
		}} else {{
			total -= 1
		}}
	}}
	return total
}}

func Sweep(limit int) int {{
	total := 0
	for k := 0; k < limit; k++ {{
		total += Classify(Triangle) + k
	}}
	return total
}}

func Fib(n int) int {{
	if n < 2 {{
		return n
	}}
	return Fib(n-1) + Fib(n-2)
}}

func Compute(seed int) int {{
	v := Vec2{{X: seed, Y: seed + {base}}}
	w := v.Add(Vec2{{X: 2, Y: 3}}).Scale(2)
	node := Node{{ID: seed, Weight: {base}, Label: "n"}}
	tagged := node.Retag("tagged")
	p := Pair[int]{{First: w.X, Second: w.Y}}
	q := Pair[string]{{First: tagged.Label, Second: "z"}}
	boxed := Wrap[int]{{Inner: seed}}
	doubled := Mapped(boxed, func(x int) int {{ return x * 2 }})
	big := Mapped(boxed, func(x int) bool {{ return x > {base} }})
	m := UnwrapOr(Maybe(seed), 0)
	g := GradePoints(Grade(seed))
	r := Ranked(tagged) + Ranked(v)
	extra := 0
	if big {{
		extra = 1
	}}
	return p.Left() + p.Right() + w.MagnitudeSq() + Identity(doubled) + m + g + r + Accumulate({base}) +
		Sweep({base}) + Fib(8) + Classify(Hexagon) + extra + len(q.Left())
}}
'''


for i in range(COUNT):
    os.makedirs(f'{root}/mod{i}')
    open(f'{root}/mod{i}/mod.go', 'w').write(module(i))

imports = '\n'.join(f'\tm{i} "corpus/mod{i}"' for i in range(COUNT))
calls = '\n'.join(f'\ttotal += m{i}.Compute({i} + 1)' for i in range(COUNT))
open(root + '/main.go', 'w').write(f'''package main

import (
\t"fmt"
{imports}
)

func main() {{
\ttotal := 0
{calls}
\tfmt.Println(total)
}}
''')
lines = sum(len(open(os.path.join(d, f)).read().splitlines())
            for d, _, fs in os.walk(root) for f in fs if f.endswith('.go'))
print(f'{COUNT} packages, {lines} lines of Go')
